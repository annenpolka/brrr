#!/usr/bin/env bash
# Exercise mint. Exit 0 only if every case holds.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
chmod +x "$ROOT/mint"
PY="${PYTHON:-python3}"
MINT=("$PY" "$ROOT/mint.py")
passed=0
failed=0

ok() { passed=$((passed + 1)); echo "ok  $1"; }
fail() { failed=$((failed + 1)); echo "FAIL  $1" >&2; echo "      $2" >&2; }

assert_contains() {
  local hay="$1" needle="$2" label="$3"
  if [[ "$hay" == *"$needle"* ]]; then ok "$label"
  else fail "$label" "missing: $needle"
  fi
}

assert_absent() {
  local hay="$1" needle="$2" label="$3"
  if [[ "$hay" != *"$needle"* ]]; then ok "$label"
  else fail "$label" "should not contain: $needle"
  fi
}

assert_exit() {
  local got="$1" want="$2" label="$3"
  if [[ "$got" -eq "$want" ]]; then ok "$label"
  else fail "$label" "exit want=$want got=$got"
  fi
}

assert_empty() {
  local hay="$1" label="$2"
  if [[ -z "$hay" ]]; then ok "$label"
  else fail "$label" "stdout not empty: ${hay:0:200}"
  fi
}

echo "======== 1. self-test ========"
"${MINT[@]}" --self-test
ok "mint --self-test"

echo "======== 2. synthetic occupancy (OPEN then Alice) ========"
FIX="$(mktemp -d "${TMPDIR:-/tmp}/mint-demo-XXXX")"
git -C "$FIX" init -q
git -C "$FIX" config user.email mint@lab
git -C "$FIX" config user.name mint
git -C "$FIX" config commit.gpgsign false

mkdir -p "$FIX/src" "$FIX/tests"
cat > "$FIX/src/profile.py" <<'PY'
import os
def load_profile(home):
    return os.path.isdir(home)
def start():
    load_profile("/tmp/cache")
PY
cat > "$FIX/tests/test_profile.py" <<'PY'
from src.profile import load_profile
def test_tmp():
    load_profile("/tmp")
PY
cat > "$FIX/src/App.swift" <<'SWIFT'
// when the macOS PollWatcher fallback is active.
public enum WindowTitleParser {
    private static let browsers: Set<String> = ["Chrome", "Safari", "Brave Browser"]
    public static func isBrowser(_ appName: String) -> Bool {
        browsers.contains(appName)
    }
}
public func loadHome(_ path: String) -> Bool { true }
public func boot() {
    _ = loadHome("/tmp/sitbone")
    _ = WindowTitleParser.isBrowser("Brave Browser")
}
SWIFT
cat > "$FIX/tests/ParserTests.swift" <<'SWIFT'
func testChrome() {
    _ = WindowTitleParser.isBrowser("Chrome")
}
SWIFT
cat > "$FIX/src/quote.py" <<'PY'
def quote(path):
    return path
def examples():
    quote("/home/user/project")
PY
cat > "$FIX/tests/test_quote.py" <<'PY'
from src.quote import quote
def test_rel():
    quote("rel/path")
PY
git -C "$FIX" add -A
git -C "$FIX" commit -qm "open portable worlds"
C_OPEN="$(git -C "$FIX" rev-parse HEAD)"

cat > "$FIX/src/profile.py" <<'PY'
import os
def load_profile(home):
    return os.path.isdir(home)
def start():
    load_profile("/Users/alice")
PY
git -C "$FIX" add -A
git -C "$FIX" commit -qm "pin Alice home"
C_ALICE="$(git -C "$FIX" rev-parse HEAD)"

perl -pi -e 's#loadHome\("/tmp/sitbone"\)#loadHome("/Users/alice/Library/sitbone")#' "$FIX/src/App.swift"
git -C "$FIX" add -A
git -C "$FIX" commit -qm "spread Alice into Swift"
C_SPREAD="$(git -C "$FIX" rev-parse HEAD)"

cat > "$FIX/src/titles.py" <<'PY'
def extract_title(title):
    return title.split(" - ", 1)[0]
def crawl():
    extract_title("GitHub - annenpolka/sitbone · Pull Request #3 - Google Chrome")
PY
cat > "$FIX/tests/test_titles.py" <<'PY'
from src.titles import extract_title
def test_docs():
    extract_title("docs.rs - rand - Rust - Firefox")
PY
git -C "$FIX" add -A
git -C "$FIX" commit -qm "add GitHub titles"
C_TITLE="$(git -C "$FIX" rev-parse HEAD)"

set +e
alice_out="$("${MINT[@]}" -C "$FIX" "$C_ALICE" 2>/tmp/mint-alice.err)"
alice_rc=$?
set -e
echo "$alice_out"
assert_exit "$alice_rc" 1 "Alice commit exits 1 (minted a visa)"
assert_contains "$alice_out" "SPEC→BOUND" "Alice is SPEC→BOUND (/tmp was payload)"
assert_contains "$alice_out" "/Users/alice" "Alice HOME"
assert_contains "$alice_out" "load_profile" "world is load_profile"
assert_contains "$alice_out" "was" "parent polarity is evidence"
assert_absent "$alice_out" "import pytest" "default is not pytest"
assert_absent "$alice_out" "import XCTest" "default is not XCTest"
assert_absent "$alice_out" "from __future__" "default is not a Python module"
assert_absent "$alice_out" "generated by" "default has no generator banner"
assert_absent "$alice_out" "Brave" "OPEN Brave is not a birth"
assert_absent "$alice_out" "isBrowser" "OPEN isBrowser is not a birth"
assert_absent "$alice_out" "/home/user" "textbook quote is not a birth"
assert_absent "$alice_out" "erst" "not leftover natal keys"

set +e
open_out="$("${MINT[@]}" -C "$FIX" "$C_OPEN" 2>/tmp/mint-open.err)"
open_rc=$?
set -e
assert_exit "$open_rc" 0 "root OPEN commit mints nothing"
assert_empty "$open_out" "OPEN root stdout empty"

set +e
head_out="$("${MINT[@]}" -C "$FIX" 2>/tmp/mint-head.err)"
head_rc=$?
set -e
assert_exit "$head_rc" 0 "HEAD titles did not mint a visa"
assert_empty "$head_out" "HEAD default stdout empty"

set +e
spread_out="$("${MINT[@]}" -C "$FIX" "$C_SPREAD")"
spread_rc=$?
spread_show="$("${MINT[@]}" -C "$FIX" --spread "$C_SPREAD")"
set -e
assert_exit "$spread_rc" 0 "SPREAD is not a new visa (--check 0)"
assert_empty "$spread_out" "default hides SPREAD"
assert_contains "$spread_show" "SPREAD" "--spread names SPREAD"
assert_contains "$spread_show" "loadHome" "--spread world is loadHome"

set +e
q_out="$("${MINT[@]}" -q -C "$FIX" "$C_ALICE")"
q_rc=$?
set -e
assert_exit "$q_rc" 1 "quiet Alice still 1"
assert_empty "$q_out" "quiet has no stdout"

set +e
walk_out="$("${MINT[@]}" -C "$FIX" --walk --max 8 "$C_TITLE")"
walk_rc=$?
porc="$("${MINT[@]}" --porcelain -C "$FIX" "$C_ALICE")"
json="$("${MINT[@]}" --json -C "$FIX" "$C_ALICE")"
set -e
assert_exit "$walk_rc" 1 "walk exits 1 (Alice mint in range)"
assert_contains "$walk_out" "SPEC→BOUND" "walk finds the Alice mint"
assert_absent "$walk_out" "SPREAD" "walk default hides SPREAD"
assert_absent "$walk_out" "annenpolka" "GitHub title is not USER"
assert_contains "$porc" $'mint\t' "porcelain tag"
assert_contains "$porc" "SPEC→BOUND" "porcelain kind"
assert_contains "$json" '"tool": "mint"' "json names mint"
assert_absent "$json" '"tool": "stain"' "json is not stain"
assert_absent "$json" '"tool": "admit"' "json is not admit"

echo "======== 3. stain fixtures/ugly — needs history, not a snapshot ========"
UGLY="$ROOT/fixtures/ugly"
if [[ -d "$UGLY" ]]; then
  set +e
  ugly_err="$("${MINT[@]}" -C "$UGLY" 2>&1)"
  ugly_rc=$?
  set -e
  assert_exit "$ugly_rc" 2 "ugly tree without git is not a snapshot linter"
  assert_contains "$ugly_err" "not a git repository" "ugly error names git"

  UGLY_GIT="$(mktemp -d "${TMPDIR:-/tmp}/mint-ugly-XXXX")"
  cp -R "$UGLY/." "$UGLY_GIT/"
  git -C "$UGLY_GIT" init -q
  git -C "$UGLY_GIT" config user.email mint@lab
  git -C "$UGLY_GIT" config user.name mint
  git -C "$UGLY_GIT" config commit.gpgsign false
  git -C "$UGLY_GIT" add -A
  git -C "$UGLY_GIT" commit -qm "import ugly"
  set +e
  born="$("${MINT[@]}" -C "$UGLY_GIT" HEAD)"
  born_rc=$?
  set -e
  echo "$born"
  assert_exit "$born_rc" 1 "ugly root commit minted Alice"
  assert_contains "$born" "ABSENT→BOUND" "ugly from empty parent is ABSENT→BOUND"
  assert_contains "$born" "/Users/alice" "ugly Alice HOME"
  assert_absent "$born" "Brave" "ugly Brave is not a birth"
  assert_absent "$born" "import pytest" "ugly birth is not a test file"
  rm -rf "$UGLY_GIT"
else
  echo "(skip fixtures/ugly — not present)"
fi

echo "======== 4. sitbone / kizu (likely zero visa-births) ========"
SITBONE="${SITBONE:-$HOME/ghq/github.com/annenpolka/sitbone}"
KIZU="${KIZU:-$HOME/ghq/github.com/annenpolka/kizu}"

if [[ -d "$SITBONE/.git" ]]; then
  set +e
  sb_out="$("${MINT[@]}" -C "$SITBONE" 2>/tmp/mint-sitbone.err)"
  sb_rc=$?
  set -e
  echo "sitbone HEAD rc=$sb_rc"
  echo "$sb_out"
  if [[ "$sb_rc" -eq 2 ]]; then
    fail "sitbone HEAD runs" "$(cat /tmp/mint-sitbone.err)"
  else
    ok "sitbone HEAD runs"
  fi
  assert_absent "$sb_out" "import pytest" "sitbone is not a test file"
  assert_absent "$sb_out" "generated by" "sitbone has no generator"

  set +e
  sbw_out="$("${MINT[@]}" -C "$SITBONE" --walk --max 12 HEAD 2>/tmp/mint-sitbone-walk.err)"
  sbw_rc=$?
  set -e
  echo "sitbone --walk 12 rc=$sbw_rc"
  echo "$sbw_out"
  if [[ "$sbw_rc" -eq 2 ]]; then
    fail "sitbone walk runs" "$(cat /tmp/mint-sitbone-walk.err)"
  else
    ok "sitbone walk runs"
  fi
  # False-birth guard: Brave / GitHub titles / leftover names are not visas.
  assert_absent "$sbw_out" "Brave Browser" "sitbone walk does not mint Brave"
  assert_absent "$sbw_out" "erst" "sitbone walk is not natal keys"
else
  echo "(skip sitbone — not present)"
fi

if [[ -d "$KIZU/.git" ]]; then
  set +e
  kz_out="$("${MINT[@]}" -C "$KIZU" 2>/tmp/mint-kizu.err)"
  kz_rc=$?
  kzw_out="$("${MINT[@]}" -C "$KIZU" --walk --max 40 --summary HEAD 2>/tmp/mint-kizu-walk.err)"
  kzw_rc=$?
  kzw_body="$("${MINT[@]}" -C "$KIZU" --walk --max 40 HEAD 2>/tmp/mint-kizu-walk2.err)"
  set -e
  echo "kizu HEAD rc=$kz_rc"
  echo "$kz_out"
  echo "kizu --walk summary rc=$kzw_rc"
  echo "$kzw_out"
  echo "$kzw_body"
  if [[ "$kz_rc" -eq 2 ]]; then
    fail "kizu HEAD runs" "$(cat /tmp/mint-kizu.err)"
  else
    ok "kizu HEAD runs"
  fi
  if [[ "$kzw_rc" -eq 2 ]]; then
    fail "kizu walk runs" "$(cat /tmp/mint-kizu-walk.err)"
  else
    ok "kizu walk runs (no AbsoluteLinkError)"
  fi
  assert_absent "$kz_out" "/home/user" "kizu textbook is not a birth"
  assert_absent "$kz_out" "John Doe" "kizu quoting fixture is not a birth"
  assert_absent "$kzw_body" "/home/user" "kizu walk textbook is not a birth"
  assert_absent "$kzw_body" "John Doe" "kizu walk quoting fixture is not a birth"
  assert_absent "$kzw_out" "Traceback" "kizu walk has no traceback"
else
  echo "(skip kizu — not present)"
fi

rm -rf "$FIX"

echo
echo "passed=$passed failed=$failed"
if [[ "$failed" -ne 0 ]]; then
  exit 1
fi
exit 0
